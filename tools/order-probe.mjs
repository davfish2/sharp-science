import { chromium } from 'playwright';
const out = process.argv[2], base = 'http://localhost:8888';
const b = await chromium.launch();
const ctx = await b.newContext({ viewport: { width: 1440, height: 900 } });
await ctx.addCookies([{ name: 'ss_entry', value: '1', url: base }]);
const p = await ctx.newPage(); const errs = [];
p.on('pageerror', e => errs.push(String(e).slice(0, 200)));
await p.goto(base + '/product/griffin-beaker-250ml/'); await p.click('.buy button'); await p.waitForSelector('#cart-drawer:not([hidden]) .mini');
await p.goto(base + '/checkout/', { waitUntil: 'networkidle' });
await p.fill('#email', 'test@example.com'); await p.fill('#shipping-first_name', 'Demo'); await p.fill('#shipping-last_name', 'Customer');
await p.fill('#shipping-address_1', '1 Lab Street'); await p.fill('#shipping-city', 'Perth'); await p.fill('#shipping-postcode', '6000');
await p.waitForTimeout(1500);
await p.click('.wc-block-components-checkout-place-order-button'); await p.waitForTimeout(1500);
console.log('blocked url', p.url().includes('order-received') ? 'NOT BLOCKED' : 'still on checkout', '| error:', await p.locator('.wc-block-components-validation-error').allTextContents());
await p.getByLabel(/trade or professional customer/).check();
await p.click('.wc-block-components-checkout-place-order-button');
await p.waitForURL(/order-received/, { timeout: 30000 });
await p.waitForTimeout(800);
await p.screenshot({ path: `${out}-received.png`, fullPage: true });
console.log(p.url(), errs);
await b.close();
